package tj.mahram.lifetrack.core.i18n

import tj.mahram.lifetrack.domain.model.ProblemPriority
import tj.mahram.lifetrack.domain.model.ProblemStatus

/**
 * Localized strings for the Problems / Calendar / Analytics / Reminders features.
 *
 * These live in their own data class (held by [AppStrings.problems]) on purpose:
 * [AppStrings] already had ~250 constructor parameters and folding another ~100 in
 * pushed its generated constructor past the Dalvik `invoke-range` register limit
 * (255), which made ART reject the class at load with a VerifyError. Splitting the
 * newer strings out keeps each constructor small. [AppStrings] forwards to here so
 * call sites keep using `strings.problemsTitle` etc. unchanged.
 */
data class ProblemStrings(
    // ── Problems ──────────────────────────────────────────────
    val tabProblems: String,
    val problemsTitle: String,
    val problemsSubtitle: (active: Int, total: Int) -> String,
    val problemsEmptyTitle: String,
    val problemsEmptySubtitle: String,
    val problemsSectionActive: String,
    val problemsSectionInProgress: String,
    val problemsSectionResolved: String,
    val problemsViewList: String,
    val problemsViewCalendar: String,
    val problemsViewAnalytics: String,
    val problemPriorityLow: String,
    val problemPriorityMedium: String,
    val problemPriorityHigh: String,
    val problemPriorityLabel: String,
    val problemStatusActive: String,
    val problemStatusInProgress: String,
    val problemStatusResolved: String,
    val problemStatusLabelField: String,
    val problemFieldSolutions: String,
    val problemFieldActionPlan: String,
    val problemFieldCategory: String,
    val problemFieldCategoryPlaceholder: String,
    val problemProgressLabel: String,
    val problemHistoryTitle: String,
    val problemNoHistory: String,
    val problemDueLabel: String,
    val problemNoDue: String,
    val problemEditAction: String,
    val problemDeleteAction: String,
    val problemMarkResolved: String,
    val problemReopen: String,
    val problemUpdateProgress: String,
    // Add / edit problem sheet
    val addProblemTitle: String,
    val addProblemSubtitle: String,
    val editProblemTitle: String,
    val addProblemFieldTitle: String,
    val addProblemPlaceholderTitle: String,
    val addProblemFieldDescription: String,
    val addProblemDescPlaceholder: String,
    val addProblemSolutionsPlaceholder: String,
    val addProblemActionPlanPlaceholder: String,
    val addProblemErrorTitle: String,
    val addProblemCreateButton: String,
    // History event messages
    val historyCreated: String,
    val historyStatusChanged: (to: String) -> String,
    val historyProgress: (Int) -> String,
    val historyEdited: String,
    val historyPriorityChanged: (to: String) -> String,
    // ── Calendar ──────────────────────────────────────────────
    val calendarDay: String,
    val calendarWeek: String,
    val calendarMonth: String,
    val calendarToday: String,
    val calendarNothing: String,
    val calendarProblemsLabel: (Int) -> String,
    val calendarTasksLabel: (Int) -> String,
    val calendarMarkProgress: String,
    val calendarSelectDayHint: String,
    // ── Analytics ─────────────────────────────────────────────
    val analyticsCreated: String,
    val analyticsResolved: String,
    val analyticsActiveLabel: String,
    val analyticsResolutionRate: String,
    val analyticsThisWeek: String,
    val analyticsThisMonth: String,
    val analyticsProgressTitle: String,
    val analyticsTopCategories: String,
    val analyticsNoData: String,
    val analyticsUncategorized: String,
    // ── Reminders / notifications ─────────────────────────────
    val remindersTitle: String,
    val remindersSubtitle: String,
    val remindersManageEntry: String,
    val remindersEntrySub: String,
    val reminderEmptyTitle: String,
    val reminderEmptySubtitle: String,
    val reminderAddButton: String,
    val reminderNewTitle: String,
    val reminderEditTitle: String,
    val reminderMessageField: String,
    val reminderMessagePlaceholder: String,
    val reminderTimeField: String,
    val reminderFrequencyField: String,
    val reminderFreqDaily: String,
    val reminderFreqWeekdays: String,
    val reminderFreqWeekends: String,
    val reminderFreqCustom: String,
    val reminderDaysField: String,
    val reminderEnabledLabel: String,
    val reminderSaveButton: String,
    val reminderDeleteAction: String,
    val reminderDefaultMessage: String,
    val reminderNotifTitle: String,
    // ── Dashboard problems / profile ──────────────────────────
    val dashboardProblemsLabel: String,
    val dashboardActiveProblems: String,
    val dashboardProblemsCount: (active: Int, total: Int) -> String,
    val dashboardNoProblems: String,
    val profileStatProblems: String,
) {
    fun problemPriorityName(priority: ProblemPriority): String = when (priority) {
        ProblemPriority.LOW    -> problemPriorityLow
        ProblemPriority.MEDIUM -> problemPriorityMedium
        ProblemPriority.HIGH   -> problemPriorityHigh
    }

    fun problemStatusLabel(status: ProblemStatus): String = when (status) {
        ProblemStatus.ACTIVE      -> problemStatusActive
        ProblemStatus.IN_PROGRESS -> problemStatusInProgress
        ProblemStatus.RESOLVED    -> problemStatusResolved
    }
}

